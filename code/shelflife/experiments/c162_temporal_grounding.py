"""C162: inconsistent timelines on TempEvalQA-Bi (Qiu et al., arXiv 2311.08398v2).

Default few_shot is the released GPT-4 three-example protocol (Table 2: Inc 27.23%,
paired accuracy67.41%). One item holds both opposing questions, submitted independently
with identical system/prefix; no conversation between them. Source GPT-4 branch passes
no decoding params (API defaults), despite CLI flags requesting T=0 and max_tokens=2.
We preserve that branch. Runtime policy may add a cap; that adaptation is logged.

The authors GPT2-tokenize each article, slice ids[1:-1] (or ids[1:cap-1] at cap),
then decode with default English tokenization cleanup. GPT2 has no added BOS/EOS,
so this accidentally removes real boundary tokens. This quirk is preserved. Prepared
prompts are generated by the original pure functions using pinned tokenizer JSON.
The original transformers version was not specified; v4.35.2 cleanup is pinned here.

Original scorer: strip/lower/replace true->yes,false->no; label SUBSTRING matching.
Paired accuracy requires each expected label occur in its response. Inconsistency is
XOR of (original expected label found in original response) and (negative expected
label found in negative response), conditional on at least one yes/no substring in
either response. Both-no-answer pairs are excluded only from inconsistency, retained
as incorrect for paired accuracy. This can treat 'I do not know' as containing 'no',
credit contradictory prose, and miss neither/both label output formats. Headline keeps
that rule; strict-label diagnostics and reliability flags expose these cases. Missing
calls are unavailable pairs; available empty text follows original no-answer rule.
Truncated text is scored as saved and counted. Bootstrap clusters are event pairs;
document-cluster CI is an additional dependence sensitivity (many pairs share text).

Items: all224 released event pairs; deterministic seed162, proportionally interleaved
(domain, original yes/no label) ordering. Each pair contributes one yes and one no
reference; source-side labels are208yes/16no and this distribution is preserved. --limit counts PAIRS, two requests each.
zero_shot is another original Table2 protocol (Inc31.25%, paired accuracy64.29%).
zero_shot_panel is explicitly nonfaithful: zero-shot prompts with cap1024 and
min_cap_reasoning16384 for budgeted panel use. Original
zero_shot full224 is the conservative later-panel recommendation. Default remains
the original few-shot protocol for the27.23% anchor.

Robustness variants:
robust_parse = zero_shot_panel (all 224 pairs, same paired requests) scored with
options parse='robust'; robust = robust_parse + truncated='score' for new panel runs.
_robust.cap_floor(max_tokens 1024) leaves 1024 and the policy min_cap_reasoning stays
16384, there are no logprobs/seed/top_k, so robust's REQUESTS ARE BYTE-IDENTICAL to
zero_shot_panel's (and robust_parse's); only fingerprints differ (options). Saved
zero_shot_panel runs (M015/M204) are therefore valid robust rows when rescored.
parse='robust': per response the paper substring rule runs first (strip/lower,
true->yes/false->no, 'yes'/'no' substring; GPT-2 preprocessing and the strict-order
assumption kept). It "yields nothing" only when the response has neither substring;
only then is _robust.extract_yes_no (markdown/<think>/answer-marker normalisation,
negation- and ambiguity-aware) tried. Because bold, 'Final answer: Yes' and <think>
text all contain the substrings, the paper rule already reads them, so the fallback
can fire only when markup splits the word (e.g. 'Y**es**'); parsed_robust is expected
to be ~0. Documented robust != paper exceptions on rows the paper scored: NONE (the
pair score equals the paper score whenever either response has a substring; a pair
with no substring on both sides is the paper's excluded no-answer pair either way).
Reported (robust variants): parsed_paper / parsed_robust / unparsed_responses (per
response), unparsed (pairs: no-answer pairs, or a complete response with no answer),
missing (failed calls; under robust_parse also pairs with a cut-off response,
truncated='missing'), truncated_scored (robust: cut pairs scored by the paper rule on
their text, no answer -> wrong), validity_rate, paired accuracy alongside the
inconsistency headline, and marker_label_inconsistency_DIAGNOSTIC (_robust labels only).
headline_reliable = _robust.reliable(n, unparsed, missing) AND at most 10% of pairs
with an ambiguous substring (both 'yes' and 'no' in one response, where the paper rule
credits whichever label is expected; e.g. '<think>..no..</think> Yes', 'I know') or a
response read only through a 'no' inside a refusal-like phrase ('I don't know', 'does not
specify', 'cannot be determined'; refusal_like_no_DIAGNOSTIC, audit m1; counted once per
pair as suspect_substring_pairs). The score itself stays the paper score. Audit m2: a
cut-off no-answer pair under robust is unparsed only, not truncated_scored.
Under robust variants the field 'unparsed' changes meaning (old strict-label count
moves to strict_unparsed_DIAGNOSTIC). Faithful/panel variants are unchanged.
"""
