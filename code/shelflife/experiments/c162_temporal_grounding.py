@functools.lru_cache(None)
def data():
    return tuple(json.loads(line) for line in (ROOT / 'prepared.jsonl').read_text().splitlines() if line)

def paper_normalize(text):
    return text.strip().lower().replace('true','yes').replace('false','no')

def strict_label(text):
    """Diagnostic only; never substitutes for the paper's substring rule."""
    match = re.fullmatch(r'\s*(yes|no|true|false)[.!]?\s*',text,re.I)
    return {'true':'yes','false':'no'}.get(match[1].lower(),match[1].lower()) if match else None

class TemporalPair(Program):
    name = 'independent_before_after_pair'
    def __init__(self, variant):
        self.variant=variant
        self.case_extra = {'min_cap_reasoning':16384} if variant.options.get('panel_cap') else {}
    def messages(self,item,direction):
        return [{'role':'system','content':self.variant.prompts['system'].render()},
                {'role':'user','content':item['prompts'][self.variant.options['setting']][direction]}]
    def preview(self,item): return self.messages(item,'original')
    def forward(self,item,lm):
        output={}
        for direction in ('original','negative'):
            c=lm(self.messages(item,direction),self.variant.params,step=direction)
            output[direction]={'content':c.content,'status':c.status,'finish_reason':c.finish_reason,'usage':c.usage,'raw_usage':c.raw_usage}
        return output

@register
class TemporalGrounding(Experiment):
    claim_id='C162'
    title='Models give inconsistent answers about event timelines'
    claim='Models answer before/after questions inconsistently on TempEvalQA-Bi.'
    paper={'title':'Are Large Language Models Temporally Grounded?', 'url':'https://arxiv.org/abs/2311.08398v2',
           'authors':'Qiu et al.','year':2023}
    source=SOURCE
    default_variant='few_shot'
    maturity='ready'
    def build_variants(self):
        deviations=('Original transformers version unspecified; GPT2 fast tokenizer + v4.35.2 default cleanup pinned.',
                    'API route policy may impose an output cap; original GPT-4 branch set none.')
        prompts={'system':SYSTEM,'user':USER,'few_shot_prefix':PREFIX}
        fs=Variant('few_shot','Original GPT-4 three-example TempEvalQA-Bi protocol',prompts=prompts,
                   params={},strategy='independent_paired_queries',options={'setting':'few_shot'},deviations=deviations)
        zs=Variant('zero_shot','Original GPT-4 zero-shot TempEvalQA-Bi protocol',prompts={'system':SYSTEM,'user':USER},
                   params={},strategy='independent_paired_queries',options={'setting':'zero_shot'},deviations=deviations)
        zs_panel=zs.override('zero_shot_panel',description='Zero-shot original prompts, explicit panel output allowance',
                          params={'max_tokens':1024},options={'panel_cap':True},
                          deviations=('Output cap1024 with reasoning-route floor16384; original GPT-4 set no cap.',))
        rp=zs_panel.override('robust_parse',description='zero_shot_panel requests (all 224 pairs) scored with parse=robust',
                          options={'parse':'robust'},
                          deviations=('parse=robust: paper substring rule per response first; _robust.extract_yes_no only '
                                      'for a response with neither yes nor no substring; reliable when <=10% of pairs '
                                      'are unparsed or missing and <=10% have an ambiguous yes+no substring; '
                                      'cut-off pairs are missing (truncated=missing).',))
        rb=rp.override('robust',description='robust_parse for new panel runs: identical requests to zero_shot_panel '
                       '(cap_floor keeps max_tokens 1024, min_cap_reasoning 16384); cut-off responses scored',
                       params=_robust.cap_floor(zs_panel.params),options={'truncated':'score'},
                       deviations=('truncated=score: a response cut off at the 1024/16384 cap is scored by the paper '
                                   'rule on its text (no answer -> wrong) and counted truncated_scored.',))
        return {v.name:v for v in (fs,zs,zs_panel,rp,rb)}
    def items(self,variant,limit=None):
        groups=defaultdict(list)
        for item in data(): groups[(item['domain'],item['original']['answer'].lower())].append(item)
        rng=random.Random(162)
        for key in sorted(groups): rng.shuffle(groups[key])
        ordered=[]
        sizes={k:len(v) for k,v in groups.items()}
        taken={k:0 for k in groups}
        total=sum(sizes.values())
        while any(groups.values()):
            # Largest deficit gives every prefix approximately source-proportional strata.
            keys=[k for k in sorted(groups) if groups[k]]
            key=max(keys,key=lambda k:(len(ordered)+1)*sizes[k]/total-taken[k])
            ordered.append(groups[key].pop()); taken[key]+=1
        return ordered[:limit] if limit is not None else ordered
    def program(self,variant): return TemporalPair(variant)
    def score(self,item,output,variant):
        a=paper_normalize(output['original'].get('content') or '')
        b=paper_normalize(output['negative'].get('content') or '')
        label=item['original']['answer'].lower(); neg=item['negative']['answer'].lower()
        yes_a=label in a; yes_b=neg in b
        noanswer=(label not in a and label not in b and neg not in b and neg not in a)
        parsed=[strict_label(output[d].get('content') or '') for d in ('original','negative')]
        strict_valid=all(x is not None for x in parsed)
        out={'correct':yes_a and yes_b,'inconsistent':(yes_a != yes_b) and not noanswer,
                'has_answer':not noanswer,'no_answer':noanswer,'unparsed':not strict_valid,
                'strict_labels':parsed,'strict_inconsistent':(parsed[0]==parsed[1]) if strict_valid else None,
                'strict_correct':(parsed==[label,neg]) if strict_valid else None,
                'ambiguous_substring':any('yes' in x and 'no' in x for x in (a,b)),
                'truncated':any(output[d].get('status')=='truncated' or output[d].get('finish_reason')=='length' for d in ('original','negative'))}
        if variant.options.get('parse','paper')=='robust':
            out.update(robust_pair(item,output,_robust.truncation_missing(variant)))
        return out
    def aggregate(self,rows,variant):
        if variant.options.get('parse','paper')=='robust':
            return self._robust_aggregate(rows,variant)
        eligible=lambda r:r.get('score') is not None and r['score']['has_answer']
        out=stats.rate_summary(rows,lambda r:r['score']['inconsistent'],usable=eligible)
        out['inconsistency']=out['rate']
        out['paired_accuracy']=stats.rate_summary(rows,lambda r:r['score']['correct'])
        out['no_answer']=sum(r['score']['no_answer'] for r in rows if r.get('score') is not None)
        out['missing_pairs']=sum(r.get('score') is None for r in rows)
        for name in ('unparsed','ambiguous_substring','truncated'):
            out[name]=sum(bool(r['score'][name]) for r in rows if r.get('score') is not None)
        out['strict_inconsistency_DIAGNOSTIC']=stats.rate_summary(rows,lambda r:r['score']['strict_inconsistent'],
                usable=lambda r:r.get('score') is not None and not r['score']['unparsed'])
        available=[r for r in rows if eligible(r)]
        def statistic(rs): return sum(r['score']['inconsistent'] for r in rs)/len(rs) if rs else None
        _,lo,hi=stats.cluster_bootstrap(available,cluster=lambda r:(r['item']['domain'],r['item']['document']),statistic=statistic)
        out['document_cluster_ci95_DIAGNOSTIC']=[lo,hi]
        reliable=bool(rows) and out['missing_pairs']==0 and out['unparsed']/len(rows)<=.05 and out['truncated']==0
        out['headline_reliable']=reliable
        out['shelflife']=Headline(metric='inconsistency',value=out['rate'],n=out['scored'],direction=1,
            unit='fraction',null_value=0,paper_value=.2723 if variant.options['setting']=='few_shot' else .3125,
            denominator='Event pairs with an answer substring in at least one direction (paper rule)',
            ci=out['ci95'] if out['rate'] is not None else None,missing=out['missing_pairs'],
            missingness_note='No-answer pairs excluded by author rule, counted separately; bounds include both no-answer and unavailable pairs.',
            headline_reliable=reliable,
            reliability_note='Original substring rule; pairs share narratives, see document-cluster sensitivity; strict ordering assumed.').to_dict()
        return out
    def _robust_aggregate(self,rows,variant):
        """parse='robust' summary: paper-equal headline where the substring rule reads either response; tolerant
        reliability (_robust.reliable) plus an ambiguous-substring guard; parse-path counts."""
        ok=lambda r:r.get('score') is not None and not r['score']['robust_missing']
        eligible=lambda r:ok(r) and r['score']['robust_has_answer']
        out=stats.rate_summary(rows,lambda r:r['score']['robust_inconsistent'],usable=eligible)
        out['inconsistency']=out['rate']
        out['paired_accuracy']=stats.rate_summary(rows,lambda r:r['score']['robust_correct'],usable=ok)
        scores=[r['score'] for r in rows if ok(r)]
        n=len(rows)
        missing=n-len(scores)
        paths=[p for sc in scores for p in sc['parse_paths']]
        unparsed=sum(sc['robust_unparsed'] for sc in scores)
        ambiguous=sum(bool(sc['ambiguous_substring']) for sc in scores)
        refusal_like=sum(bool(sc['refusal_like_no']) for sc in scores)
        suspect=sum(bool(sc['ambiguous_substring'] or sc['refusal_like_no']) for sc in scores)
        out.update(parse='robust',parsed_paper=paths.count('paper'),parsed_robust=paths.count('robust'),
                   unparsed_responses=paths.count(None),unparsed=unparsed,missing=missing,
                   missing_pairs=sum(r.get('score') is None for r in rows),
                   missing_truncated=sum(r.get('score') is not None and r['score']['robust_missing'] for r in rows),
                   truncated_scored=sum(sc['truncated_scored'] for sc in scores),
                   no_answer=sum(not sc['robust_has_answer'] for sc in scores),ambiguous_substring=ambiguous,
                   refusal_like_no_DIAGNOSTIC=refusal_like,suspect_substring_pairs=suspect,
                   truncated=sum(bool(r['score']['truncated']) for r in rows if r.get('score') is not None),
                   strict_unparsed_DIAGNOSTIC=sum(bool(sc['unparsed']) for sc in scores),
                   validity_rate=(n-unparsed-missing)/n if n else None)
        out['strict_inconsistency_DIAGNOSTIC']=stats.rate_summary(rows,lambda r:r['score']['strict_inconsistent'],
                usable=lambda r:ok(r) and not r['score']['unparsed'])
        out['marker_label_inconsistency_DIAGNOSTIC']=stats.rate_summary(
                rows,lambda r:r['score']['marker_labels'][0]==r['score']['marker_labels'][1],
                usable=lambda r:ok(r) and None not in r['score']['marker_labels'])
        available=[r for r in rows if eligible(r)]
        def statistic(rs): return sum(r['score']['robust_inconsistent'] for r in rs)/len(rs) if rs else None
        _,lo,hi=stats.cluster_bootstrap(available,cluster=lambda r:(r['item']['domain'],r['item']['document']),statistic=statistic)
        out['document_cluster_ci95_DIAGNOSTIC']=[lo,hi]
        reliable=_robust.reliable(n,unparsed,missing) and _robust.reliable(n,suspect)
        out['headline_reliable']=reliable
        out['shelflife']=Headline(metric='inconsistency',value=out['rate'],n=out['scored'],direction=1,
            unit='fraction',null_value=0,paper_value=.2723 if variant.options['setting']=='few_shot' else .3125,
            denominator='Event pairs with an answer in at least one direction (paper substring rule, then _robust fallback)',
            ci=out['ci95'] if out['rate'] is not None else None,missing=missing,
            missingness_note='No-answer pairs excluded by author rule and counted unparsed; missing = failed calls'
                             +(' and cut-off pairs.' if _robust.truncation_missing(variant) else '.'),
            headline_reliable=reliable,
            reliability_note=f'parse=robust: <=10% unparsed+missing pairs and <=10% ambiguous-substring or refusal-like-no pairs; '
                             f'validity {out["validity_rate"]}; paired accuracy {out["paired_accuracy"]["rate"]}; strict order assumed.').to_dict()
        return out
    targets=(
        PaperTarget('GPT4_few_shot_inconsistency',.2723,.00005,'arXiv2311.08398v2 Table2 GPT4 few-shot Inc.',
                    'gpt-4','few_shot','archived_outputs',compute=lambda e:archived_metrics(e,'few_shot')['inconsistency']),
        PaperTarget('GPT4_few_shot_accuracy',.6741,.00005,'arXiv2311.08398v2 Table2 GPT4 few-shot Acc.',
                    'gpt-4','few_shot','archived_outputs',compute=lambda e:archived_metrics(e,'few_shot')['paired_accuracy']['rate']),
        PaperTarget('GPT4_zero_shot_inconsistency',.3125,.00005,'arXiv2311.08398v2 Table2 GPT4 zero-shot Inc.',
                    'gpt-4','zero_shot','archived_outputs',compute=lambda e:archived_metrics(e,'zero_shot')['inconsistency']),
        PaperTarget('GPT4_zero_shot_accuracy',.6429,.00005,'arXiv2311.08398v2 Table2 GPT4 zero-shot Acc.',
                    'gpt-4','zero_shot','archived_outputs',compute=lambda e:archived_metrics(e,'zero_shot')['paired_accuracy']['rate']),
        PaperTarget('event_pairs',224,0,'arXiv2311.08398v2 Section3.1','dataset','few_shot','released_data',compute=lambda e:len(e.items(e.variant()))),)

def robust_label(text):
    """parse='robust' per-response label: (label, path). The paper substring rule first: if the paper-normalized text
    contains 'yes' or 'no' the paper rule has read it (path 'paper', label None: the pair is then scored by the paper
    booleans, which test each expected label as a substring). Otherwise _robust.extract_yes_no on the raw text."""
    a=paper_normalize(text or '')
    if 'yes' in a or 'no' in a:
        return None,'paper'
    lab=_robust.extract_yes_no(text or '')
    return (lab.lower(),'robust') if lab else (None,None)

REFUSAL_NO=re.compile(r"(?:don'?t|do not|does not|doesn'?t|did not|didn'?t) (?:know|specify|mention|say|state|provide|indicate|give)"
                      r"|\b(?:unknown|unclear|insufficient|not (?:sure|certain|specified|mentioned|stated|clear|provided|given|"
                      r"possible|enough)|no (?:information|way to|indication|mention)|(?:cannot|can'?t|unable to|impossible to)"
                      r" (?:be )?(?:determine|determined|tell|say|know|answer|infer))")

def refusal_like_no(text):
    """Diagnostic (audit m1): the paper rule reads this response only through a 'no' substring inside a refusal-like
    phrase ('I don't know', 'does not specify', 'cannot be determined', 'not mentioned'): no 'yes' substring, the
    text does not open with the word 'no', and a refusal phrase is present. Never changes the score."""
    a=paper_normalize(text or '')
    return 'yes' not in a and 'no' in a and not re.match(r'\W*no\b',a) and bool(REFUSAL_NO.search(a))

def robust_pair(item,output,cut_missing=True):
    """parse='robust' pair fields. Equal to the paper booleans whenever the substring rule reads a response."""
    label=item['original']['answer'].lower(); neg=item['negative']['answer'].lower()
    hits,paths,cuts,markers=[],[],[],[]
    for d,expected in (('original',label),('negative',neg)):
        text=output[d].get('content') or ''
        lab,path=robust_label(text)
        hits.append(expected in paper_normalize(text) if path=='paper' else lab==expected)
        paths.append(path)
        cuts.append(output[d].get('status')=='truncated' or output[d].get('finish_reason')=='length')
        m=_robust.extract_yes_no(text)
        markers.append(m.lower() if m else None)
    has_answer=any(p is not None for p in paths)
    cut=any(cuts)
    missing=cut and cut_missing
    # A complete response with no answer is unparsed; a cut one (truncated='score') is a scored failure, unless
    # the whole pair has no answer, where the paper rule gives no value: then the pair is unparsed too.
    unparsed=not missing and (not has_answer or any(p is None and not c for p,c in zip(paths,cuts)))
    return {'robust_correct':hits[0] and hits[1],'robust_inconsistent':(hits[0]!=hits[1]) and has_answer,
            'robust_has_answer':has_answer,'parse_paths':paths,'robust_unparsed':unparsed,'robust_missing':missing,
            'truncated_scored':cut and not cut_missing and has_answer,'marker_labels':markers,
            'refusal_like_no':any(refusal_like_no(output[d].get('content') or '') for d in ('original','negative'))}

def archived_rows(exp,setting):
    rows=[]
    folder={'few_shot':'few-shot-icl','zero_shot':'zero-shot'}[setting]
    texts={}
    for domain in DOMAINS:
        for direction in ('original','negative'):
            texts[(domain,direction)]=(REPO/f'gpt-output/tempeval-qa-bi/{folder}/tempeval-{domain}-gpt-4-{direction}.out').read_text().splitlines()
    variant=exp.variant(setting)
    for item in exp.items(variant):
        output={d:{'content':texts[(item['domain'],d)][item['source_index']]} for d in ('original','negative')}
        rows.append({'item':item,'output':output,'score':exp.score(item,output,variant),'repeat':0,'model':'gpt-4','status':'complete'})
    return rows

def archived_metrics(exp,setting='few_shot'):
    return exp.aggregate(archived_rows(exp,setting),exp.variant(setting))
